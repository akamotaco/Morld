def build_focus_rules(archetype, activities, default_text,
                      *, specials=None, order=None):
    """FOCUS_RULES 빌더 — 아키타입 공유 템플릿 + NPC별 활동/기본값.

    모브 NPC는 archetype + activities + default_text만 지정하면
    정액/체내정액/성욕/호감/mood 묘사를 자동 상속.
    """
    sections = {
        "carrying": _FOCUS_CARRYING,
        "restraint": _FOCUS_RESTRAINT,
        "assault_victim": _FOCUS_ASSAULT_VICTIM,
        "npc_intimacy": _FOCUS_NPC_INTIMACY,
        "climax": _FOCUS_CLIMAX.get(archetype, []),
        "exposure_body": _FOCUS_EXPOSURE_BODY.get(archetype, []),
        "shame": _FOCUS_SHAME.get(archetype, []),
        "specials": list(specials or []),
        "semen": _FOCUS_SEMEN,
        "internal_semen": _FOCUS_INTERNAL_SEMEN.get(archetype, []),
        "idle_flavor": (
            _DESCRIBE_IDLE_ARCHETYPE.get(archetype, []) + _DESCRIBE_IDLE_COMMON
        ),
        "activity": [({"activity": k}, v) for k, v in activities],
        "mood": _FOCUS_MOOD.get(archetype, []),
        "desire": _FOCUS_DESIRE.get(archetype, []),
        "affection": _FOCUS_AFFECTION.get(archetype, []),
        "menstruation": _FOCUS_MENSTRUATION.get(archetype, []),
        "personality": _FOCUS_PERSONALITY,
        "default": [({}, default_text)],
    }
    rules = []
    for section in (order or _DEFAULT_FOCUS_ORDER):
        rules.extend(sections[section])
    return rules


