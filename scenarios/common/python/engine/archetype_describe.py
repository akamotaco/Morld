_DESCRIBE_CARRYING = [
    ({"carrying": True}, "{name}(이)가 {carried_name}을(를) 업고 있다."),
]


def build_describe_rules(archetype, *, traveling=None, activities=None,
                         locations=None, weather=None, default_text="",
                         specials=None, order=None):
    """DESCRIBE_RULES 빌더 — 아키타입 공유 템플릿 + NPC별 이동/활동/위치.

    모브 NPC는 archetype + activities + default_text만 지정하면
    정액/체내정액/성욕/호감/피로도 묘사를 자동 상속.
    """
    sections = {
        "carrying": _DESCRIBE_CARRYING,
        "restraint": _DESCRIBE_RESTRAINT,
        "assault_victim": _DESCRIBE_ASSAULT_VICTIM,
        "npc_intimacy": _DESCRIBE_NPC_INTIMACY,
        "masturbation": _DESCRIBE_MASTURBATION,
        "parasite": _DESCRIBE_PARASITE,
        "parasite_reaction": _DESCRIBE_PARASITE_REACTION.get(archetype, []),
        "climax": _DESCRIBE_CLIMAX.get(archetype, []),
        "exposure_body": _DESCRIBE_EXPOSURE_BODY.get(archetype, []),
        "shame": _DESCRIBE_SHAME.get(archetype, []),
        "specials": list(specials or []),
        "traveling": list(traveling or []),
        "idle_flavor": (
            _DESCRIBE_IDLE_ARCHETYPE.get(archetype, []) + _DESCRIBE_IDLE_COMMON
        ),
        "activity": [({"activity": k}, v) for k, v in (activities or [])],
        "location": list(locations or []),
        "weather": list(weather or []),
        "semen": _DESCRIBE_SEMEN,
        "internal_semen": _DESCRIBE_INTERNAL_SEMEN.get(archetype, []),
        "desire": _DESCRIBE_DESIRE.get(archetype, []),
        "affection": _DESCRIBE_AFFECTION.get(archetype, []),
        "menstruation": _DESCRIBE_MENSTRUATION.get(archetype, []),
        "default": [({}, default_text)],
        "fatigue": _DESCRIBE_FATIGUE.get(archetype, []),
    }
    rules = []
    for section in (order or _DEFAULT_DESCRIBE_ORDER):
        rules.extend(sections[section])
    return rules



