# ============================================

def get_aftermath_text(name, event_type, stage, archetype, count=1):
    """아키타입 기반 aftermath 텍스트 선택.

    Args:
        name: NPC 이름 ({name} 치환용)
        event_type: "forced" | "unconscious" | "frozen" | "bestiality"
        stage: 3 (충격) | 2 (경계) | 1 (잔향)
        archetype: 10개 아키타입 중 하나
        count: 누적 피해 횟수

    Returns:
        str: 포맷팅된 텍스트
    """
    # count >= 2 + stage 3 → 반복 템플릿 우선
    if count >= 2 and stage == 3:
        pool = REPEAT_TEMPLATES.get(event_type, {}).get(archetype)
        if pool:
            return random.choice(pool).format(name=name)

    # 표준 템플릿
    pool = TEMPLATES.get(event_type, {}).get(stage, {}).get(archetype)
    if pool:
        return random.choice(pool).format(name=name)

    # fallback
    return _FALLBACK.get(event_type, "({name}(이)가 이상한 기분인 것 같다...)").format(name=name)
