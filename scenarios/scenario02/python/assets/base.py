    @staticmethod
    def _calculate_exposure(unit_id):
        """의상 기반 노출 상태 계산

        Returns:
            dict: upper(0-2), lower(0-2), score(0-100)
            - 0=완전커버, 1=속옷, 2=완전노출
        """
        import equipment as _eq
        equipped = _eq.get_equipped_items(unit_id)
        has = {"상의": False, "속옷상의": False, "하의": False, "속옷하의": False}
        sexy_count = 0

        for item_id in equipped:
            info = morld.get_item_info(item_id)
            if not info:
                continue
            ep = info.get("equip_props", {})
            if ep.get("착용:상의"):
                has["상의"] = True
            if ep.get("착용:속옷상의"):
                has["속옷상의"] = True
            if ep.get("착용:하의"):
                has["하의"] = True
            if ep.get("착용:속옷하의"):
                has["속옷하의"] = True
            if ep.get("분위기:섹시함"):
                sexy_count += 1

        # 부위별 노출 수준
        if not has["상의"] and not has["속옷상의"]:
            upper = 2
        elif not has["상의"]:
            upper = 1
        else:
            upper = 0

        if not has["하의"] and not has["속옷하의"]:
            lower = 2
        elif not has["하의"]:
            lower = 1
        else:
            lower = 0

        # 임시노출 override (성추행 들추기)
        temp_upper = morld.get_unit_prop(unit_id, "임시노출:상체") or 0
        temp_lower = morld.get_unit_prop(unit_id, "임시노출:하체") or 0
        upper = max(upper, temp_upper)
        lower = max(lower, temp_lower)

        # 총합 노출도 (0-100)
        score = upper * 25 + lower * 25 + min(20, sexy_count * 5)
        if has["상의"] and not has["속옷상의"]:
            score += 5
        if has["하의"] and not has["속옷하의"]:
            score += 5

        return {"upper": upper, "lower": lower, "score": min(100, score)}

