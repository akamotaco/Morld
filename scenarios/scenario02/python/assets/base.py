    def _build_context(self) -> dict:
        """
        현재 상태를 context dict로 변환

        서브클래스에서 오버라이드하여 추가 context 제공 가능.
        """
        info = morld.get_unit_info(self.instance_id)
        if not info:
            return {"name": self.name}

        # 기본 정보
        # Job.Name이 "오전활동:독서" 형태일 수 있음 → 실제 활동명만 추출
        raw_activity = info.get("activity")
        activity = raw_activity.split(":")[-1] if raw_activity and ":" in raw_activity else raw_activity

        context = {
            "name": info.get("name", self.name),
            "activity": activity,
            "mood": info.get("mood", []),
            "is_traveling": info.get("is_traveling", False),
            "region_id": info.get("region_id"),
            "location_id": info.get("location_id"),
        }

        # 위치 튜플 (조건에서 사용)
        context["location"] = (context["region_id"], context["location_id"])

        # Props에서 호감도, 진척도 등 가져오기
        props = morld.get_unit_props(self.instance_id)
        player_id = morld.get_player_id()
        player_info = morld.get_unit_info(player_id)
        player_name = player_info.get("name", "주인공") if player_info else "주인공"

        if props:
            context["호감"] = props.get(f"관계:{player_name}:호감", 0)
            context["진척도"] = props.get(f"관계:{player_name}:진척도", 0)
            context["성욕"] = props.get("상태:성욕", 0)
            # 정액 오염
            _semen_parts = ["얼굴", "가슴", "배", "음부", "엉덩이"]
            semen_total = sum(props.get(f"오염물:정액:{p}", 0) for p in _semen_parts)
            context["정액"] = semen_total
            for p in _semen_parts:
                context[f"정액:{p}"] = props.get(f"오염물:정액:{p}", 0)
            # 체내 정액
            _internal_parts = ["음부", "항문", "구강"]
            internal_total = 0
            for ip in _internal_parts:
                val = props.get(f"체내:정액:{ip}", 0)
                context[f"체내정액:{ip}"] = val
                internal_total += val
            context["체내정액"] = internal_total
            # 도구 분실 플래그
            for key, value in props.items():
                if key.startswith("도구분실:"):
                    context[key] = value

        # 위치 정보에서 날씨, 실내 여부 가져오기
        location_info = morld.get_location_info(
            context["region_id"],
            context["location_id"]
        )
        if location_info:
            context["weather"] = location_info.get("weather")
            context["is_indoor"] = location_info.get("is_indoor", True)

        # idle flavor (think 시스템에서 설정)
        from think.idle_flavors import get_flavor
        context["flavor"] = get_flavor(self.instance_id)

        # 근처 오브젝트 인식
        from assets.objects import get_location_objects
        r_id = context["region_id"]
        l_id = context["location_id"]
        if r_id is not None and l_id is not None:
            nearby = []
            obj_ids = get_location_objects(r_id, l_id)
            for obj_id in obj_ids:
                if morld.get_unit_prop(obj_id, "heat:output"):
                    nearby.append("열원")
                if morld.get_unit_prop(obj_id, "can:cook"):
                    nearby.append("조리대")
                if morld.get_unit_prop(obj_id, "can:sit"):
                    nearby.append("좌석")
            context["nearby"] = nearby
        else:
            context["nearby"] = []

        # 데이트 상태 확인
        from date import is_on_date, get_date_partner
        if is_on_date(player_id) and get_date_partner(player_id) == self.instance_id:
            context["on_date"] = True
        else:
            context["on_date"] = False

        # 플레이어 체력 역전 (HP 낮을수록 높은 값 → >= 비교 편의)
        player_hp = morld.get_unit_prop(player_id, "생존:체력")
        context["피로도_체력"] = max(0, 100 - (player_hp if player_hp is not None else 100))

        # 결박 상태 (상체/하체 분리)
        import restraint as _restraint
        context["upper_restrained"] = _restraint.is_upper_restrained(self.instance_id)
        context["lower_restrained"] = _restraint.is_lower_restrained(self.instance_id)
        context["restrained"] = context["upper_restrained"] or context["lower_restrained"]
        context["gagged"] = _restraint.is_gagged(self.instance_id)
        context["blindfolded"] = _restraint.is_blindfolded(self.instance_id)

        # 절정 수치
        context["절정"] = props.get("상태:절정", 0) if props else 0

        # 삽입물
        if props:
            context["삽입물_음부"] = bool(props.get("삽입물:음부"))
            context["삽입물_항문"] = bool(props.get("삽입물:항문"))
            context["삽입물_클리토리스"] = bool(props.get("삽입물:클리토리스"))
        else:
            context["삽입물_음부"] = False
            context["삽입물_항문"] = False
            context["삽입물_클리토리스"] = False

        # 노출도 / 수치심
        exposure = self._calculate_exposure(self.instance_id)
        context["노출도"] = exposure["score"]
        context["상체노출"] = exposure["upper"]   # 0=커버, 1=속옷, 2=누드
        context["하체노출"] = exposure["lower"]   # 0=커버, 1=속옷, 2=누드
        context["수치심"] = min(100, int(exposure["score"] * self.shame_sensitivity))

        # 전투 상태
        unit_id = self.instance_id
        hp = morld.get_unit_prop(unit_id, "생존:체력")
        max_hp = morld.get_unit_prop(unit_id, "생존:최대체력")
        if hp is not None and max_hp and max_hp > 0:
            context["hp_ratio"] = hp / max_hp
        else:
            context["hp_ratio"] = 1.0
        context["독"] = bool(morld.get_unit_prop(unit_id, "상태:독"))
        context["출혈"] = bool(morld.get_unit_prop(unit_id, "상태:출혈"))
        try:
            import combat as _combat
            context["마비"] = bool(_combat.is_paralyzed(unit_id))
            context["거미줄"] = bool(_combat.is_web_bound(unit_id))
        except ImportError:
            context["마비"] = False
            context["거미줄"] = False

        # 기생 상태
        try:
            import parasite as _parasite
            context["기생체"] = _parasite.has_any_parasite(unit_id)
            for _slot in _parasite.PARASITE_SLOTS:
                _part = _slot.split(":")[1]
                context[f"기생:{_part}"] = bool(
                    morld.get_unit_prop(unit_id, _slot))
        except ImportError:
            context["기생체"] = False

        # 월경/배란 상태
        try:
            import pregnancy as _pregnancy
            context["월경"] = _pregnancy.is_menstruating(unit_id)
            context["배란"] = _pregnancy.is_ovulating(unit_id)
        except Exception:
            context["월경"] = False
            context["배란"] = False

        # 겁탈 피해 중 / NPC 성행위 중
        context["겁탈피해중"] = bool(morld.get_unit_prop(unit_id, "상태:겁탈피해중"))
        context["NPC성행위중"] = bool(morld.get_unit_prop(unit_id, "상태:NPC성행위중"))
        context["NPC강제피해중"] = bool(morld.get_unit_prop(unit_id, "상태:NPC강제피해중"))

        # 운반 상태
        import carry as _carry
        carried_id = _carry.get_carried_unit(self.instance_id)
        if carried_id:
            context["carrying"] = True
            carried_info = morld.get_unit_info(carried_id)
            context["carried_name"] = carried_info.get("name", "???") if carried_info else "???"
        else:
            context["carrying"] = False
            context["carried_name"] = ""

        return context

