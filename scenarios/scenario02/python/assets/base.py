    def _check_reaction_condition(self, condition: dict, props: dict, player_name: str) -> bool:
        """
        리액션 조건 체크 (ROMANCE_REACTIONS, STEALTH_REACTIONS 등에서 공통 사용)

        조건 키 매핑:
        - "호감", "욕망", "복종", "반발" → "관계:{player_name}:{key}"
        - "성욕", "성적절정" → "상태:{key}"
        - 그 외 → 그대로 사용
        """
        if not condition:
            return True

        for key, required_value in condition.items():
            # once 마커: 조건 판정이 아닌 메타 플래그 → 스킵
            if key == "once":
                continue

            # 미경험 조건: prop이 0 또는 None이면 True
            if key.startswith("미경험:"):
                actual_key = key[4:]  # "미경험:" 이후
                actual_value = morld.get_unit_prop(self.instance_id, actual_key) or 0
                if actual_value != 0:
                    return False
                continue

            # 플레이어 체력 역전값 (HP 낮을수록 높음)
            if key == "피로도_체력":
                player_id = morld.get_player_id()
                player_hp = morld.get_unit_prop(player_id, "생존:체력") if player_id else 100
                actual_value = max(0, 100 - (player_hp if player_hp is not None else 100))
                if actual_value < required_value:
                    return False
                continue

            if key in ("호감", "욕망", "복종", "반발"):
                prop_key = f"관계:{player_name}:{key}"
            elif key in ("성욕", "성적절정"):
                prop_key = f"상태:{key}"
            else:
                prop_key = key

            actual_value = props.get(prop_key, 0) if props else 0
            if actual_value < required_value:
                return False

        return True

