def get_witness_reaction(name, archetype, reaction_type):
    """목격 반응 텍스트 반환.

    Args:
        name: NPC 이름 (템플릿 {name} 치환)
        archetype: NPC 아키타입 (stoic, gentle, cheerful, timid, cold 등)
        reaction_type: 반응 유형 (initiate, intimate, embarrassed, disgusted)

    Returns:
        str: 반응 텍스트
    """
    templates = WITNESS_TEMPLATES.get(reaction_type, {})
    pool = templates.get(archetype)

    # fallback: stoic
    if not pool:
        pool = templates.get("stoic", [f"({name}(이)가 당신을 바라본다.)"])

    text = random.choice(pool)
    return text.replace("{name}", name)
