_FALLBACK = "({name}(이)가 지난번 일을 기억하는 듯 짧게 미소 짓는다.)"


# ============================================
# API
# ============================================

def get_positive_memory_text(name, memory_type, archetype, item_name=None):
    """긍정 기억 반응 텍스트 선택.

    Args:
        name: NPC 이름 ({name} 치환)
        memory_type: "gift_favorite" / "gift_liked" / "gift_normal"
        archetype: 10개 아키타입 중 하나
        item_name: 아이템 표시 이름 ({item} 치환, None이면 "선물"로 대체)

    Returns:
        str: 포맷팅된 텍스트
    """
    pool = TEMPLATES.get(memory_type, {}).get(archetype)
    if pool:
        text = random.choice(pool)
    else:
        text = _FALLBACK

    return text.format(name=name, item=item_name or "선물")
