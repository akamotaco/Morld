# ============================================
# 단계 판정
# ============================================

def _arousal_tier(arousal):
    if arousal >= 80:
        return "extreme"
    if arousal >= 60:
        return "high"
    if arousal >= 30:
        return "medium"
    return "low"


def _gauge_tier(gauge):
    if gauge >= 80:
        return "critical"
    if gauge >= 60:
        return "high"
    if gauge >= 30:
        return "medium"
    return "low"


