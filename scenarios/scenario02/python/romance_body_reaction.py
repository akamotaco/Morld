def get_body_reaction(archetype, name, arousal, gauge, climax_total=0):
    """성격별 신체 반응 묘사 반환

    Args:
        archetype: 성격 아키타입 (stoic/gentle/cheerful/timid/cold/seductive/fierce/proud/innocent/devoted)
        name: NPC 이름
        arousal: 성욕 수치 (0-100)
        gauge: 절정 게이지 (0-100)
        climax_total: 세션 내 절정 횟수

    Returns:
        str or None: 포맷된 텍스트 (None = 반응 없음)
    """
    # 절정 후 저각성 → 절정 후 반응
    if climax_total >= 1 and arousal < 30:
        pool = _POST_CLIMAX_REACTIONS.get(archetype,
                                          _POST_CLIMAX_REACTIONS.get("stoic"))
        if pool:
            return random.choice(pool).format(name=name)
        return None

    a_tier = _arousal_tier(arousal)
    g_tier = _gauge_tier(gauge)

    # low/low → 반응 없음
    if a_tier == "low" and g_tier == "low":
        return None

    # 아키타입 풀 조회
    archetype_pool = _BODY_REACTIONS.get(archetype,
                                         _BODY_REACTIONS.get("stoic", {}))
    pool = archetype_pool.get((a_tier, g_tier))

    # 정확한 키가 없으면 가까운 키 fallback
    if not pool:
        # gauge 한 단계 낮춰서 시도
        _TIER_ORDER = ["low", "medium", "high", "critical"]
        g_idx = _TIER_ORDER.index(g_tier) if g_tier in _TIER_ORDER else 0
        if g_idx > 0:
            pool = archetype_pool.get((a_tier, _TIER_ORDER[g_idx - 1]))
        # arousal 한 단계 낮춰서 시도
        if not pool:
            _A_ORDER = ["low", "medium", "high", "extreme"]
            a_idx = _A_ORDER.index(a_tier) if a_tier in _A_ORDER else 0
            if a_idx > 0:
                pool = archetype_pool.get((_A_ORDER[a_idx - 1], g_tier))

    if not pool:
        return None

    return random.choice(pool).format(name=name)
