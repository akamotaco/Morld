# ─────────────────────────────────────────────
# LineGenerator 클래스
# ─────────────────────────────────────────────

class LineGenerator:
    """말투(speech level) + 2D 좌표(호감×욕망) + 동적 전환 기반 대사 생성기.

    네임드 NPC: ROMANCE_REACTIONS 우선, generator는 fallback.
    모브 NPC: REACTION_PROFILE만으로 전체 대사 자동 생성.
    """

    def __init__(self, profile):
        self.profile = profile
        self.name = profile["name"]
        self.archetype = profile.get("archetype", "stoic")
        self.speech_level = profile.get(
            "speech_level",
            ARCHETYPE_SPEECH.get(self.archetype, "casual"))
        self._speech_shifts = profile.get(
            "speech_shifts",
            ARCHETYPE_SPEECH_SHIFTS.get(self.archetype, {}))
        self._overrides = profile.get("line_overrides", {})

    def _resolve_speech_level(self, state):
        """상태에 따른 실효 말투 결정 — arousal → affection 순서."""
        base = self.speech_level
        shifts = self._speech_shifts

        # 1) 흥분 기반 (arousal tier → 말투 전환)
        arousal = resolve_arousal_tier(state.get("성욕", 0))
        arousal_shifts = shifts.get("arousal", {})
        if arousal in arousal_shifts:
            return arousal_shifts[arousal]

        # 2) 호감 기반 (close = 호감≥70)
        affection = state.get("호감", 0)
        affection_shifts = shifts.get("affection", {})
        if affection >= 70 and "close" in affection_shifts:
            return affection_shifts["close"]

        return base

    def generate(self, action_id, state):
        """1인칭 대사 생성 — 특수 키 → override → 행위 템플릿 → 카테고리 fallback.

        Returns:
            대사 텍스트 또는 None
        """
        tone = resolve_tone(state.get("호감", 0), state.get("욕망", 0))
        arousal = resolve_arousal_tier(state.get("성욕", 0))
        speech = self._resolve_speech_level(state)

        # 1) 특수 키 (first_*, pull_out_*, ecstasy*)
        special = self._try_special(action_id, speech, tone)
        if special:
            return special

        # 2) 캐릭터 override
        key = f"{action_id}:start"
        override_texts = self._overrides.get(key)
        if override_texts:
            return self._pick_from_nested(override_texts, speech, tone)

        # 3) 행위별 아키타입 템플릿
        text = self._try_action_template(action_id, speech, tone, arousal)
        if text:
            return text

        # 4) 카테고리 fallback
        text = self._try_category_fallback(action_id, speech, tone, arousal)
        if text:
            return text

        return None

    def _try_special(self, action_id, speech, tone):
        """first_*/pull_out_*/ecstasy* 특수 키 처리."""
        if action_id.startswith("first_"):
            body = action_id[6:]  # "first_vaginal_penetration" → "vaginal_penetration"
            return self._pick_first(body, speech, tone)

        if action_id.startswith("pull_out_"):
            rest = action_id[9:]  # "pull_out_얼굴" or "pull_out_얼굴_heavy"
            return self._pick_pull_out(rest, speech, tone)

        if action_id.startswith("ecstasy"):
            return self._pick_ecstasy(action_id, speech, tone)

        return None

    def _pick_first(self, body_part, speech, tone):
        """첫 경험 대사."""
        templates = FIRST_LINE_TEMPLATES.get(body_part, {})
        return self._pick_speech_tone(templates, speech, tone)

    def _pick_pull_out(self, rest, speech, tone):
        """사정 반응 대사 — heavy 판별 포함."""
        if rest.endswith("_heavy"):
            body_part = rest[:-6]
            pool = PULL_OUT_HEAVY_LINE_TEMPLATES
        else:
            body_part = rest
            pool = PULL_OUT_LINE_TEMPLATES
        templates = pool.get(body_part, {})
        return self._pick_speech_tone(templates, speech, tone)

    def _pick_ecstasy(self, action_id, speech, tone):
        """절정 반응 대사."""
        templates = ECSTASY_LINE_TEMPLATES.get(action_id, {})
        return self._pick_speech_tone(templates, speech, tone)

    def _try_action_template(self, action_id, speech, tone, arousal):
        """ACTION_LINE_TEMPLATES에서 아키타입별 조회."""
        key = f"{action_id}:start"
        templates = ACTION_LINE_TEMPLATES.get(key, {})
        arch_block = templates.get(self.archetype, {})

        # arousal-specific: key:start:{arousal} 조회
        if arousal in ("extreme", "high"):
            arousal_key = f"{key}:{arousal}"
            arousal_templates = ACTION_LINE_TEMPLATES.get(arousal_key, {})
            arousal_block = arousal_templates.get(self.archetype, {})
            text = self._pick_speech_tone(arousal_block, speech, tone)
            if text:
                return text

        return self._pick_speech_tone(arch_block, speech, tone)

    def _try_category_fallback(self, action_id, speech, tone, arousal):
        """LINE_TEMPLATES 카테고리에서 fallback."""
        category = ACTION_TO_CATEGORY.get(action_id)
        if not category:
            return None

        cat_key = f"{category}:start"

        # arousal-specific category
        if arousal in ("extreme", "high"):
            arousal_templates = LINE_TEMPLATES.get(f"{cat_key}:{arousal}", {})
            text = self._pick_speech_tone(arousal_templates, speech, tone)
            if text:
                return text

        # base category
        base_templates = LINE_TEMPLATES.get(cat_key, {})
        return self._pick_speech_tone(base_templates, speech, tone)

    def _pick_speech_tone(self, speech_dict, speech, tone):
        """speech_dict[speech][tone] → random.choice, tone fallback 포함."""
        if not speech_dict:
            return None

        tone_dict = speech_dict.get(speech, {})
        if not tone_dict:
            return None

        texts = tone_dict.get(tone)
        if texts:
            return random.choice(texts)

        # tone fallback: romance/lust → try opposite, then any
        fallback_order = {
            "romance": ["lust", "platonic"],
            "lust": ["romance"],
            "platonic": ["romance"],
            "rejection": ["platonic"],
        }
        for fb in fallback_order.get(tone, []):
            texts = tone_dict.get(fb)
            if texts:
                return random.choice(texts)

        return None

    def _pick_from_nested(self, data, speech, tone):
        """override 데이터 해석 — 리스트 or dict."""
        if isinstance(data, list):
            return random.choice(data) if data else None
        if isinstance(data, dict):
            return self._pick_speech_tone(data, speech, tone)
        return None
